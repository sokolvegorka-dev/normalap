from foods_extra import extra_foods

BEST_BRANDS = {
    "AlphaPet", "AJO", "Craftia", "Craftia Galena", "Bowl Wow", "Savita", "Award",
    "Мираторг", "FLORIDA", "Blitz", "Karmy", "Mr.Buffalo", "Best Dinner", "Night Hunter",
}


def _is_best(food):
    brand = food.get("brand") or ""
    if brand == "Мираторг":
        return "Extra Meat" in (food.get("name") or "")
    return brand in BEST_BRANDS


FOODS = [
    f for f in DRY_FOODS + extra_foods(
        F, ALL_CATS, ALL_DOGS, DOG_MINI_SMALL, DOG_MEDIUM, DOG_LARGE, DOG_GIANT,
        CAT_HIGH_ENERGY, CAT_LARGE, CAT_LONGHAIR, CAT_WEIGHT,
    ) if _is_best(f)
]


def foods_for(species, tags_any=None, medical=False, sterilised=False, tier=None):
    out = []
    for f in FOODS:
        if f["species"] != species:
            continue
        tags = f["tags"]
        is_med = any(t.startswith("medical:") for t in tags)
        if medical and not is_med:
            continue
        if sterilised and "sterilised" not in tags:
            continue
        if tags_any and not any(t in tags for t in tags_any):
            continue
        if tier and f["tier"] != tier:
            continue
        out.append(f)
    return out
